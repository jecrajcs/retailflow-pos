-- Run only after migrations 0005, 0006, and 0007 are applied.
-- Replace the hash placeholder with output from:
--   node scripts/generate-admin-password-hash.mjs
-- Keep the temporary password separately; this script stores only its Better Auth hash.
-- This transaction refuses to overwrite an existing Admin or matching login identifier.

BEGIN;

DO $seed$
DECLARE
  v_user_id uuid := gen_random_uuid();
  v_auth_email text;
  v_password_hash text := 'fdbc9417a7a9695aab54bf641a296442:1a8cbc9f6b5ff463a7f9cc6b8fe65fb8d05264b0c3b9d7971b9dbadeefb13fb6bb8b781b6ab673803d1c17da4aa70d2e40e7153afd97327862c98644d6ec6303';
  v_display_name text := 'DailyPlazaa Admin';
  v_email text := 'admin@dailyplazaa.com';
  v_phone text := '+918269295929';
BEGIN
  IF v_password_hash !~ '^[0-9a-f]{32}:[0-9a-f]{128}$' THEN
    RAISE EXCEPTION 'Paste the Better Auth password hash generated by the local helper';
  END IF;

  IF EXISTS (SELECT 1 FROM public.users WHERE role = 'ADMIN') THEN
    RAISE EXCEPTION 'An Admin profile already exists; do not seed a duplicate Admin';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.users
    WHERE lower(btrim(email)) = v_email
      OR regexp_replace(COALESCE(phone, ''), '[^0-9]', '', 'g')
        IN ('8269295929', '918269295929')
  ) THEN
    RAISE EXCEPTION 'The Admin email or mobile is already assigned to a staff profile';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.auth_login_identifiers
    WHERE normalized_identifier IN (
      'email:admin@dailyplazaa.com',
      'phone:+918269295929'
    )
  ) THEN
    RAISE EXCEPTION 'The Admin email or mobile is already assigned as a login identifier';
  END IF;

  v_auth_email := 'staff-' || replace(v_user_id::text, '-', '') || '@accounts.retailflow.invalid';

  INSERT INTO public.users (
    user_id,
    display_name,
    email,
    phone,
    role,
    is_active,
    must_change_password,
    created_at,
    updated_at
  ) VALUES (
    v_user_id,
    v_display_name,
    v_email,
    v_phone,
    'ADMIN',
    true,
    true,
    now(),
    now()
  );

  INSERT INTO public.auth_users (
    id,
    name,
    email,
    email_verified,
    created_at,
    updated_at
  ) VALUES (
    v_user_id,
    v_display_name,
    v_auth_email,
    false,
    now(),
    now()
  );

  INSERT INTO public.auth_accounts (
    account_id,
    provider_id,
    user_id,
    password,
    created_at,
    updated_at
  ) VALUES (
    v_user_id::text,
    'credential',
    v_user_id,
    v_password_hash,
    now(),
    now()
  );

  INSERT INTO public.auth_login_identifiers (
    normalized_identifier,
    user_id,
    kind,
    created_at
  ) VALUES
    ('email:admin@dailyplazaa.com', v_user_id, 'email', now()),
    ('phone:+918269295929', v_user_id, 'phone', now());
END;
$seed$;

COMMIT;
